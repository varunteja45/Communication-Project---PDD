  /// Returns a list of [count] unique, non-repeating questions randomly sampled
  /// from the specified interview [type] and [difficulty].
  static List<String> getQuestions({
    required String type,
    required String difficulty,
    required int count,
  }) {
    final typeMap = _questions[type] ?? _questions['HR Interview']!;
    final pool = List<String>.from(typeMap[difficulty] ?? typeMap['Medium']!);

    // Shuffle pool to guarantee randomness and pick non-repeating subset
    pool.shuffle(_random);
    return pool.take(count.clamp(1, pool.length)).toList();
  }
